/*
 * selftest.h — прогон golden-векторов протокола на плате.
 *
 * Вектора взяты из vendor/crc_vectors.json: это единственный механический
 * мост между этой прошивкой и сервисом на Pi — репозитории разные, общей
 * сборки нет, и расхождение реализаций не поймает ни компилятор, ни CI.
 *
 * Вызывается из main() один раз до основного цикла. Печатает в USART1.
 */
#ifndef TESTS_SELFTEST_H
#define TESTS_SELFTEST_H

/* Прогоняет все проверки и печатает итог. Возвращает число провалов (0 — всё сошлось). */
unsigned selftest_run(void);

/* Печать строки в USART1, блокирующая. Годится только до старта планировщика. */
void st_puts(const char *s);

#endif /* TESTS_SELFTEST_H */
