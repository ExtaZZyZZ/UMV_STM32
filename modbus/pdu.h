/*
 * pdu.h — кадрирование Modbus RTU: проверка и сборка ADU.
 *
 * ADU = адрес слейва (1) + PDU (функция и данные) + CRC16 (2).
 * CRC считается по адресу и PDU, то есть по всему кадру кроме самого CRC,
 * и уходит в провод младшим байтом вперёд. Числа ВНУТРИ PDU, наоборот,
 * старшим байтом вперёд — отсюда две пары помощников ниже.
 *
 * Файл не знает про HAL и собирается как ARM-сборкой, так и хостовым gcc.
 */
#ifndef MODBUS_PDU_H
#define MODBUS_PDU_H

#include <stdint.h>

/* Структурный минимум кадра: адрес + функция + CRC. Осмысленные кадры длиннее,
 * но проверка длин под конкретную функцию — дело slave.c, а не кадрирования. */
#define ADU_MIN_LEN 4u

/* Предел Modbus RTU. Наш самый длинный кадр — ответ FC04 на 22 регистра,
 * 49 байт; берём предел протокола, чтобы не пересчитывать при росте карты. */
#define ADU_MAX_LEN 256u

typedef enum {
    ADU_OK = 0,
    ADU_ERR_SHORT,    /* короче структурного минимума -> frame_err */
    ADU_ERR_CRC,      /* CRC не сошёлся               -> crc_err   */
    ADU_ERR_ADDRESS,  /* кадр адресован не нам        -> frame_err */
} adu_status_t;

/* Проверяет кадр целиком. При ADU_OK кладёт в *pdu_len длину PDU — без адреса
 * и без CRC. Аргумент pdu_len может быть NULL.
 *
 * Порядок проверок — длина, CRC, адрес — обязателен: адресному байту можно
 * верить только после того, как кадр доказан целым, иначе кадр к нам с побитым
 * первым байтом будет засчитан как «чужой адрес» вместо «битый CRC», и
 * счётчики покажут диагноз, противоположный происходящему на линии. */
adu_status_t adu_check(const uint8_t *adu, uint16_t len, uint8_t slave_id, uint16_t *pdu_len);

/* Дописывает CRC после первых len байт буфера. Возвращает полную длину кадра.
 * В буфере должно быть место ещё под два байта. */
uint16_t adu_wrap(uint8_t *buf, uint16_t len);

/* Числа внутри PDU: старший байт вперёд. */
uint16_t rd_u16be(const uint8_t *p);
void     wr_u16be(uint8_t *p, uint16_t v);

#endif /* MODBUS_PDU_H */
